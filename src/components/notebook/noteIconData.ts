/** Emoji search: a name match in any category, newest first. */
export function searchNoteEmojis(query: string): string[] {
  const needle = normalize(query);
  if (!needle) return [];
  const seen = new Set<string>();
  for (const category of NOTE_EMOJI_CATEGORIES) {
    for (const item of category.items) {
      if (normalize(item.k).includes(needle) && !seen.has(item.e)) seen.add(item.e);
    }
  }
  return [...seen];
}

