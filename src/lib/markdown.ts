/**
 * تبدیل متن Markdown به متن ساده، روان و تمیز برای پیش‌نمایش در کارت‌های تسک و یادداشت.
 * علائم قالب‌بندی نظیر تیترها، چک‌باکس‌ها، نقل‌قول‌ها، بولت‌ها و ستاره‌ها را پاک‌سازی می‌کند.
 */
export function stripMarkdownForPreview(markdown: string): string {
  if (!markdown) return '';

  let text = markdown;

  // ۱. حذف بلوک‌های کد سه‌تایی
  text = text.replace(/```[\s\S]*?```/g, (match) => {
    return match.replace(/```[a-zA-Z0-9_-]*\n?/g, '').replace(/```/g, ' ');
  });

  // ۲. حذف کدهای تک‌خطی (Inline code)
  text = text.replace(/`([^`]+)`/g, '$1');

  // ۳. حذف تصاویر و لینک‌ها، نگه‌داشتن فقط متن لینک
  text = text.replace(/!\[([^\]]*)\]\([^)]*\)/g, '$1');
  text = text.replace(/\[([^\]]+)\]\([^)]*\)/g, '$1');

  // ۴. حذف چک‌باکس‌ها: `- [ ] `, `* [ ] `, `[ ] `, `- [x] `
  text = text.replace(/(?:^|\s)(?:[-*+]\s+)?\[[ xX]\]\s*/g, ' ');

  // ۵. حذف تیترها: `### `, `## `, `# ` در ابتدای خطوط یا بین متن
  text = text.replace(/(?:^|\n|\s)#{1,6}\s+/g, ' ');

  // ۶. حذف علامت‌های نقل‌قول (`> `)
  text = text.replace(/(?:^|\n|\s)>\s*/g, ' ');

  // ۷. حذف خطوط جداکننده (`---`, `***`)
  text = text.replace(/(?:^|\n)[-*_]{3,}\s*(?=\n|$)/g, ' ');

  // ۸. حذف بولت‌های لیست (`- `, `* `, `+ `)
  text = text.replace(/(?:^|\n)\s*[-*+]\s+/g, ' ');

  // ۹. حذف استایل‌های بولد، ایتالیک و استریک: `**متن**`, `*متن*`, `~~متن~~`
  text = text.replace(/[*_~]{1,3}([^*_~]+)[*_~]{1,3}/g, '$1');

  // ۱۰. جایگزینی خطوط چندگانه با یک فاصله و تمیزکاری فاصله‌ها
  text = text.replace(/\s+/g, ' ').trim();

  return text;
}
