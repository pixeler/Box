/**
 * Returns a stable quote for the given dateKey so it stays consistent
 * throughout that day and changes automatically on the next day.
 */
export function getDailyQuote(dateKey: string): string {
  if (!dateKey) return DAILY_QUOTES[0];

  let hash = 0;
  for (let i = 0; i < dateKey.length; i++) {
    hash = (hash << 5) - hash + dateKey.charCodeAt(i);
    hash |= 0;
  }

  const index = Math.abs(hash) % DAILY_QUOTES.length;
  return DAILY_QUOTES[index];
}
