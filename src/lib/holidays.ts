export const HOLIDAYS: IranianHoliday[] = RAW.map(([date, title, isOfficial]) => ({
  date,
  title,
  isOfficial,
}));

/** Map date-string → holiday (for O(1) lookup) */
const _index = new Map<string, IranianHoliday[]>();
for (const h of HOLIDAYS) {
  const arr = _index.get(h.date) ?? [];
  arr.push(h);
  _index.set(h.date, arr);
}

export function getHolidaysForDate(dateStr: string): IranianHoliday[] {
  return _index.get(dateStr) ?? [];
}

export function isOfficialHoliday(dateStr: string): boolean {
  return (_index.get(dateStr) ?? []).some(h => h.isOfficial);
}
